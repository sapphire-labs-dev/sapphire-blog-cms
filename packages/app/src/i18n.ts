const locales: Record<string, Messages> = { 'pt-BR': ptBR, pt: ptBR, en };

let messages: Messages = en;
let currentLocale = 'en';

export function setLocale(preferred?: string) {
  const candidates = [preferred, ...navigator.languages].filter(Boolean) as string[];
  const match = candidates
    .map((code) => (locales[code] ? code : locales[code.split('-')[0]] ? code.split('-')[0] : null))
    .find(Boolean);

  // Two languages for now: Portuguese, and English when nothing else matches.
  currentLocale = match === 'pt' || match === 'pt-BR' ? 'pt-BR' : 'en';
  messages = locales[currentLocale];
}

export const getLocale = () => currentLocale;

export function t(key: MessageKey, vars: Record<string, string | number> = {}) {
  return messages[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}
